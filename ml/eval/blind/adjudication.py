"""Deterministic adjudication of reviewer conflicts. Standard library only.

An adjudication is an append-only record that resolves a disagreement. It
never edits a review and never edits the narrative: the record has no field
that could hold scenario text, and unknown fields are refused, so an
adjudicator can change the *labels* under discussion and nothing else. Both
original reviews stay in the review ledger exactly as they were recorded.

Who may adjudicate
  * not the author of the sample (the repository's stated rule);
  * not one of the reviewers whose records are in conflict — a person cannot
    break a tie they are one side of. This is stricter than the minimum stated
    in the staffing policy; it applies the same independence principle the
    author rule rests on and is listed in ``STAFFING.md`` for lead sign-off;
  * marked ``can_adjudicate`` on the roster and competent in the sample's
    language, with Hinglish requiring code-switching competence.

Crisis and immediate-danger disagreements
  These are the two labels the repository requires two independent human
  reviewers for. An adjudicator is one human, so an adjudication cannot by
  itself create that agreement. When the critical labels are what conflict,
  the record may state the CONSERVATIVE routing — the most severe of the
  positions in conflict, so the case is not under-routed while the question is
  open — but the sample stays ineligible until two distinct reviewers actually
  hold the same critical view. In practice that means a third independent
  blind review, after which ``critical_conflict_resolved`` may be set and is
  checked against the review records, never taken on trust.

A ledger that does not verify blocks adjudication outright: resolving a
conflict on top of a broken chain would record a decision about records that
can no longer be proved to be the ones reviewed.
"""

import hashlib
from datetime import datetime
from typing import Any, Dict, List, Mapping, Optional, Sequence

from ..schema import BANDS, CATEGORIES, CRITICAL_CATEGORIES, DETECTOR_CATEGORIES
from .annotation import critical_view
from .assignment import CRITICAL_AGREEMENT, critical_support
from .identity import competent_for, same_person, validate_person
from .submission import canonical, narrative_sha256

RECORD_VERSION = "1.0.0"

RESOLUTION_BASES = (
    "reviewers_reconciled",      # the original reviewers recorded agreeing views
    "third_independent_review",  # a further blind review created a two-person majority
    "adjudicator_decision",      # the adjudicator decided a non-critical disagreement
)

ATTESTATION = ("I personally adjudicated this disagreement. I did not author this scenario, I did not write "
               "either of the reviews in conflict, I did not change the scenario text, and this record was "
               "not generated by an AI system.")

RECORD_FIELDS = {"record_version", "corpus_version", "submission_id", "narrative_sha256",
                 "reviewed_record_sha256", "adjudicator", "labels", "routing", "expected_evidence",
                 "expected_abstention", "resolution_basis", "conservative_routing_only",
                 "critical_conflict_resolved", "reasoning", "timestamp", "attestation", "record_sha256"}
_HASHED_FIELDS = sorted(RECORD_FIELDS - {"record_sha256"})

MIN_REASONING = 40
_SEVERITY = {band: i for i, band in enumerate(BANDS)}  # Low < Moderate < High < Critical


class AdjudicationError(Exception):
    """Adjudication is impossible, or the record is malformed."""


def record_sha256(record: Mapping[str, Any]) -> str:
    payload = {k: record[k] for k in _HASHED_FIELDS if k in record}
    return hashlib.sha256(canonical(payload).encode("utf-8")).hexdigest()


def conservative_routing(records: Sequence[Mapping[str, Any]]) -> str:
    """The most severe routing among the conflicting reviews."""
    if not records:
        raise AdjudicationError("no reviews to adjudicate")
    return max((str(r.get("routing")) for r in records), key=lambda b: _SEVERITY.get(b, -1))


def blank_record(submission_id: str, corpus_version: str, narrative_sha256: str,
                 reviews: Sequence[Mapping[str, Any]]) -> Dict[str, Any]:
    """A BLANK adjudication for a human. No decision is pre-filled."""
    return {
        "record_version": RECORD_VERSION,
        "corpus_version": corpus_version,
        "submission_id": submission_id,
        "narrative_sha256": narrative_sha256,
        "reviewed_record_sha256": sorted(str(r["record_sha256"]) for r in reviews),
        "adjudicator": {"person_id": "", "identity": "", "kind": "human", "role": "",
                        "languages": [], "code_switch_competent": False},
        "labels": {c: False for c in CATEGORIES},
        "routing": "",
        "expected_evidence": {},
        "expected_abstention": False,
        "resolution_basis": "",
        "conservative_routing_only": False,
        "critical_conflict_resolved": False,
        "reasoning": "",
        "timestamp": "",
        "attestation": "",
        "record_sha256": "",
    }


def packet(submission: Mapping[str, Any], reviews: Sequence[Mapping[str, Any]],
           comparison: Mapping[str, Any]) -> Dict[str, Any]:
    """What an adjudicator sees: the sample, and only the conflicting fields.

    Unlike a review packet this one is NOT blind — resolving a disagreement
    requires seeing both positions — but it is still narrow: the reviewers'
    decision fields and reasoning, never a system output, and never another
    adjudicator's record.
    """
    fields = list(comparison.get("conflicts") or [])
    positions = []
    for r in sorted(reviews, key=lambda x: str(x["record_sha256"])):
        positions.append({
            "record_sha256": r["record_sha256"],
            "reviewer": {"person_id": r["reviewer"]["person_id"], "role": r["reviewer"]["role"]},
            "decision": r["decision"], "routing": r["routing"], "labels": r["labels"],
            "expected_evidence": r["expected_evidence"], "expected_abstention": r["expected_abstention"],
            "confidence": r["confidence"], "reasoning": r["reasoning"],
            "ambiguity_flags": r["ambiguity_flags"],
        })
    return {
        "submission_id": submission["submission_id"],
        "corpus_version": submission["corpus_version"],
        "language": submission["language"],
        "script": submission["script"],
        "turns": submission["turns"],
        "conflicting_fields": sorted(fields),
        "critical_conflict": bool(comparison.get("critical_conflict")),
        "conservative_routing": conservative_routing(reviews),
        "copied_reasoning_flags": list(comparison.get("copied_reasoning") or []),
        "positions": positions,
        "rules": ("You may change the labels, the routing, the evidence turns and the abstention. You may not "
                  "change the scenario text, and you may not edit either review: both stay on the record. "
                  "A crisis or immediate-danger disagreement needs two reviewers who agree, so recording the "
                  "conservative routing here does not make the sample eligible."),
        "attestation_text": ATTESTATION,
        "record_template": blank_record(submission["submission_id"], submission["corpus_version"],
                                        narrative_sha256(submission), reviews),
    }


def validate_record(record: Mapping[str, Any], submission: Optional[Mapping[str, Any]] = None,
                    reviews: Sequence[Mapping[str, Any]] = ()) -> List[str]:
    """Every problem with one adjudication record. Empty means valid."""
    errs: List[str] = []
    if not isinstance(record, Mapping):
        return ["adjudication record must be a JSON object"]
    extra = set(record) - RECORD_FIELDS
    missing = RECORD_FIELDS - set(record)
    if extra:
        errs.append(f"unknown fields {sorted(extra)} (an adjudication cannot carry scenario text)")
    if missing:
        return errs + [f"missing fields {sorted(missing)}"]

    if record["record_version"] != RECORD_VERSION:
        errs.append(f"record_version must be {RECORD_VERSION}")
    errs.extend(validate_person(record["adjudicator"], "adjudicator"))

    labels = record["labels"]
    if not isinstance(labels, Mapping) or set(labels) != set(CATEGORIES):
        errs.append(f"labels must have exactly the {len(CATEGORIES)} schema categories")
        labels = {}
    else:
        for c, v in labels.items():
            if not isinstance(v, bool):
                errs.append(f"label {c} must be a bool")
    if record["routing"] not in BANDS:
        errs.append(f"routing must be one of {tuple(BANDS)}")
    if labels and any(bool(labels.get(c)) for c in CRITICAL_CATEGORIES) and record["routing"] != "Critical":
        errs.append("a crisis or immediate-danger label must be routed Critical")
    if not isinstance(record["expected_abstention"], bool):
        errs.append("expected_abstention must be a bool")
    for flag in ("conservative_routing_only", "critical_conflict_resolved"):
        if not isinstance(record[flag], bool):
            errs.append(f"{flag} must be a bool")
    if record["resolution_basis"] not in RESOLUTION_BASES:
        errs.append(f"resolution_basis must be one of {RESOLUTION_BASES}")

    evidence = record["expected_evidence"]
    if not isinstance(evidence, Mapping):
        errs.append("expected_evidence must be an object of category -> turn ids")
    else:
        victim_ids = set()
        if submission is not None:
            victim_ids = {str(t["id"]) for t in submission.get("turns", []) if t.get("speaker") == "victim"}
        for cat, ids in evidence.items():
            if cat not in DETECTOR_CATEGORIES:
                errs.append(f"expected_evidence names non-detector category {cat!r}")
                continue
            if not labels.get(cat):
                errs.append(f"expected_evidence for {cat} but the label is false")
            if not isinstance(ids, list) or not ids:
                errs.append(f"expected_evidence for {cat} is empty")
                continue
            for i in ids:
                if victim_ids and str(i) not in victim_ids:
                    errs.append(f"expected_evidence id {i!r} for {cat} is not a victim turn of this sample")
        for cat in DETECTOR_CATEGORIES:
            if labels.get(cat) and cat not in evidence:
                errs.append(f"label {cat} is true but has no expected_evidence")

    if len(str(record["reasoning"]).strip()) < MIN_REASONING:
        errs.append(f"written reasoning of at least {MIN_REASONING} characters is required")
    if record["attestation"] != ATTESTATION:
        errs.append("the adjudicator attestation sentence is missing or altered")
    try:
        ts = datetime.fromisoformat(str(record["timestamp"]))
        if ts.tzinfo is None:
            errs.append("timestamp needs a timezone offset")
    except ValueError:
        errs.append("timestamp must be ISO 8601 with a timezone")
    if record["record_sha256"] != record_sha256(record):
        errs.append("record_sha256 does not match the record")

    reviewed = record["reviewed_record_sha256"]
    if not isinstance(reviewed, list) or len(reviewed) < 2:
        errs.append("reviewed_record_sha256 must name at least the two reviews in conflict")
        reviewed = []
    elif len(set(reviewed)) != len(reviewed):
        errs.append("reviewed_record_sha256 repeats a record")

    if submission is not None:
        if record["submission_id"] != submission["submission_id"]:
            errs.append("submission_id does not match the sample")
        if record["corpus_version"] != submission["corpus_version"]:
            errs.append("corpus_version does not match the sample")
        if same_person(record["adjudicator"], submission.get("author") or {}):
            errs.append("the author of a sample cannot adjudicate it")
        if not competent_for(record["adjudicator"], submission.get("language")):
            errs.append(f"adjudicator is not recorded as competent in {submission.get('language')}")

    if reviews:
        known = {str(r["record_sha256"]): r for r in reviews}
        for rid in reviewed:
            if str(rid) not in known:
                errs.append("reviewed_record_sha256 names a record that is not in the review ledger "
                            "for this sample")
        narratives = {str(r.get("narrative_sha256")) for r in reviews}
        if narratives and record["narrative_sha256"] not in narratives:
            errs.append("narrative_sha256 does not match the text the reviewers annotated")
        for r in reviews:
            if str(rid_of(r)) in {str(x) for x in reviewed} and same_person(record["adjudicator"], r["reviewer"]):
                errs.append("a reviewer whose record is in conflict cannot adjudicate that conflict")
                break

        crit_conflict = len({canonical(critical_view(r)) for r in reviews}) > 1
        support = critical_support(reviews, record)
        if record["critical_conflict_resolved"]:
            if support < CRITICAL_AGREEMENT:
                errs.append(f"critical_conflict_resolved needs {CRITICAL_AGREEMENT} distinct reviewers holding "
                            f"the adjudicated critical view; {support} do")
            if record["resolution_basis"] == "adjudicator_decision":
                errs.append("a critical disagreement cannot be resolved by an adjudicator's decision alone")
        elif crit_conflict and not record["conservative_routing_only"]:
            errs.append("an unresolved critical disagreement must record conservative_routing_only")
        if record["conservative_routing_only"]:
            want = conservative_routing(reviews)
            if record["routing"] != want:
                errs.append(f"conservative_routing_only requires the most severe routing in conflict ({want})")
    return errs


def rid_of(record: Mapping[str, Any]) -> str:
    return str(record.get("record_sha256", ""))


def eligible_after_adjudication(record: Mapping[str, Any], reviews: Sequence[Mapping[str, Any]]) -> List[str]:
    """Reasons this adjudicated sample is still NOT eligible. Empty means it is."""
    reasons: List[str] = []
    labels = record.get("labels") or {}
    critical = any(bool(labels.get(c)) for c in CRITICAL_CATEGORIES) or record.get("routing") == "Critical"
    crit_conflict = len({canonical(critical_view(r)) for r in reviews}) > 1
    if critical or crit_conflict:
        if not record.get("critical_conflict_resolved"):
            reasons.append("critical label conflict is not explicitly resolved under the two-reviewer policy")
        elif critical_support(reviews, record) < CRITICAL_AGREEMENT:
            reasons.append(f"critical labels rest on fewer than {CRITICAL_AGREEMENT} agreeing reviewers")
    if record.get("conservative_routing_only"):
        reasons.append("only the conservative routing was recorded; the label question is still open")
    return reasons
