"""Blinded review packets and the review-record schema. Standard library only.

What a reviewer sees
  The packet carries the submission id, the language and script, the turns,
  the label definitions, the permitted values, the evidence and abstention
  instructions, and a blank record for them to fill. Nothing else.

What the packet CANNOT contain, structurally rather than by promise
  * detector output, SVI, band, alerts, pipeline evidence — this package never
    imports a module that can produce them (``firewall.py``);
  * the author's expected routing — an author submission has no label and no
    expected-outcome field at all, so there is nothing to leak;
  * the author's identity, the declared challenge slices and the lineage — a
    slice name such as ``explicit_negation`` is the answer written on the
    front of the envelope, so ``build_packet`` copies a fixed allow-list of
    keys and drops everything else;
  * another reviewer's decision — packets are built per reviewer from the
    submission, never from the review ledger;
  * baseline failure reports and whether the system currently passes: no
    module here reads ``ml/eval/results/``.

The reviewer re-hashes what they were shown (``narrative_sha256``) and copies
that hash into their record, so a record can be proved to describe the exact
text the author submitted. A reviewer cannot alter the submission: their
record is a separate document in a separate ledger, and the freeze gate reads
the narrative only from the author-submission ledger.
"""

import hashlib
from datetime import datetime
from typing import Any, Dict, List, Mapping, Optional, Sequence

from ..schema import BANDS, CATEGORIES, CRITICAL_CATEGORIES, DETECTOR_CATEGORIES
from .identity import competent_for, validate_person
from .submission import canonical, narrative_sha256

RECORD_VERSION = "1.0.0"
PACKET_VERSION = "1.0.0"

DECISIONS = ("accept", "reject", "needs_discussion")
CONFIDENCE = ("low", "medium", "high")
ROUTINGS = tuple(BANDS)  # Low, Moderate, High, Critical

#: Why a reviewer was unsure. A closed vocabulary so the flags can be counted.
AMBIGUITY_FLAGS = (
    "scope_of_negation_unclear",
    "speaker_attribution_unclear",
    "tense_unclear",
    "severity_borderline",
    "language_or_dialect_uncertain",
    "transliteration_ambiguous",
    "insufficient_context",
    "possible_real_case_material",
    "possible_stereotype_dependence",
    "slice_declaration_looks_wrong",
)

ATTESTATION = ("I personally annotated this scenario. I did not see any system output, score, band, routing "
               "or evaluation result for it, I did not see another reviewer's decision, and this record was "
               "not generated by an AI system.")

#: Short, reviewer-facing definitions. They restate ml/eval/schema.py; the
#: schema module remains the authority and a change there must be mirrored here.
LABEL_DEFINITIONS: Dict[str, str] = {
    "crisis_self_harm":
        "The person speaking for themself expresses present suicidal intent, a wish to die, or self-harm. "
        "Risk words that are denied, or that belong to someone else, are NOT this label.",
    "immediate_danger":
        "Danger that is present or imminent: someone at the door now, coming tonight, a weapon now. "
        "A threat about the future is continuing_threat instead.",
    "continuing_threat":
        "Threat, intimidation or pressure directed at the person or their family, including pressure to "
        "withdraw a complaint. It need not be imminent.",
    "medical_urgency":
        "Someone is injured, bleeding, unconscious or needs treatment now. Mild pain alone is not.",
    "isolation_boycott_displacement":
        "Social boycott, denial of water, shops or work, being forced to leave, or nobody being allowed to "
        "speak to them.",
    "legal_urgency":
        "A complaint, FIR, police refusal, court or hearing matter that needs action or information.",
    "communication_safety_coercion":
        "The person cannot speak freely (someone is listening, the phone is checked) or is being coerced "
        "about speaking or complaining.",
    "explicit_human_request":
        "The person asks, in words, for a human being.",
    "negated_risk_language":
        "Risk vocabulary appears but is explicitly negated within its own clause.",
    "quoted_attributed_risk":
        "Risk vocabulary appears only as someone else's words or as a report of something else.",
    "adversarial_injection":
        "The text tries to instruct or manipulate the system: ignore your instructions, set my risk low, "
        "roleplay as somebody, tell me my score.",
}

ROUTING_DEFINITIONS: Dict[str, str] = {
    "Critical": "A human must take over immediately. Any crisis or confirmed immediate danger is Critical.",
    "High": "Needs a human today; serious but not immediate.",
    "Moderate": "Needs follow-up in the normal queue.",
    "Low": "Information or routine support; no alert is warranted.",
}

EVIDENCE_INSTRUCTIONS = (
    "For every category you mark true, list the victim turn ids that carry it, and only those. "
    "If a category is true only because of something said in a later turn, name that later turn. "
    "Do not list a turn merely because it sets the scene. Do not list assistant or officer turns."
)
ABSTENTION_INSTRUCTIONS = (
    "Mark expected_abstention true when a correct system would refuse to produce a score at all and hand the "
    "case to a person: the text is too short or too unclear to assess, the language is uncertain, or the "
    "meaning turns on something you cannot resolve. Abstention is a correct answer, not a failure. If you "
    "mark abstention, still give the labels you are confident about and leave the rest false."
)
BLINDING_NOTICE = (
    "You are annotating blind. You have not been shown any system output for this scenario and you must not "
    "seek one out, run the pipeline on it, or discuss it with another reviewer before both records are "
    "recorded. If you have already seen a system result for this text, stop and tell the corpus owner."
)

PACKET_FIELDS = ("packet_version", "packet_id", "corpus_version", "submission_id", "language", "script",
                 "turns", "narrative_sha256", "label_definitions", "permitted_labels", "permitted_routings",
                 "evidence_instructions", "abstention_instructions", "ambiguity_flags", "blinding_notice",
                 "attestation_text", "record_template")
#: Anything from a submission that is NOT in this allow-list never reaches a packet.
VISIBLE_SUBMISSION_KEYS = ("submission_id", "corpus_version", "language", "script", "turns")

RECORD_FIELDS = {"record_version", "corpus_version", "packet_id", "submission_id", "narrative_sha256",
                 "reviewer", "decision", "labels", "routing", "expected_evidence", "expected_abstention",
                 "confidence", "reasoning", "ambiguity_flags", "timestamp", "attestation", "record_sha256"}
_HASHED_FIELDS = sorted(RECORD_FIELDS - {"record_sha256"})

MIN_REASONING = 25


class AnnotationError(Exception):
    """A packet or a review record is malformed."""


def packet_id(submission: Mapping[str, Any], reviewer: Mapping[str, Any]) -> str:
    """Deterministic id binding one submission to one reviewer."""
    payload = {"submission_id": str(submission.get("submission_id")),
               "corpus_version": str(submission.get("corpus_version")),
               "narrative_sha256": narrative_sha256(submission),
               "reviewer_person_id": str(reviewer.get("person_id"))}
    return hashlib.sha256(canonical(payload).encode("utf-8")).hexdigest()[:32]


def blank_record(submission: Mapping[str, Any], reviewer: Mapping[str, Any]) -> Dict[str, Any]:
    """An empty record. Every judgement field is blank; validation refuses blanks."""
    return {
        "record_version": RECORD_VERSION,
        "corpus_version": submission["corpus_version"],
        "packet_id": packet_id(submission, reviewer),
        "submission_id": submission["submission_id"],
        "narrative_sha256": narrative_sha256(submission),
        "reviewer": {"person_id": reviewer.get("person_id", ""), "identity": reviewer.get("identity", ""),
                     "kind": "human", "role": reviewer.get("role", ""),
                     "languages": list(reviewer.get("languages") or []),
                     "code_switch_competent": bool(reviewer.get("code_switch_competent", False))},
        "decision": "",
        "labels": {c: False for c in CATEGORIES},
        "routing": "",
        "expected_evidence": {},
        "expected_abstention": False,
        "confidence": "",
        "reasoning": "",
        "ambiguity_flags": [],
        "timestamp": "",
        "attestation": "",
        "record_sha256": "",
    }


def build_packet(submission: Mapping[str, Any], reviewer: Mapping[str, Any]) -> Dict[str, Any]:
    """One blinded packet. Copies an allow-list of keys and nothing else."""
    visible = {k: submission[k] for k in VISIBLE_SUBMISSION_KEYS}
    return {
        "packet_version": PACKET_VERSION,
        "packet_id": packet_id(submission, reviewer),
        "corpus_version": visible["corpus_version"],
        "submission_id": visible["submission_id"],
        "language": visible["language"],
        "script": visible["script"],
        "turns": visible["turns"],
        "narrative_sha256": narrative_sha256(submission),
        "label_definitions": dict(LABEL_DEFINITIONS),
        "permitted_labels": {c: [True, False] for c in CATEGORIES},
        "permitted_routings": {r: ROUTING_DEFINITIONS[r] for r in ROUTINGS},
        "evidence_instructions": EVIDENCE_INSTRUCTIONS,
        "abstention_instructions": ABSTENTION_INSTRUCTIONS,
        "ambiguity_flags": list(AMBIGUITY_FLAGS),
        "blinding_notice": BLINDING_NOTICE,
        "attestation_text": ATTESTATION,
        "record_template": blank_record(submission, reviewer),
    }


def record_sha256(record: Mapping[str, Any]) -> str:
    """Hash over every record field except the hash itself."""
    payload = {k: record[k] for k in _HASHED_FIELDS if k in record}
    return hashlib.sha256(canonical(payload).encode("utf-8")).hexdigest()


def validate_record(record: Mapping[str, Any], packet: Optional[Mapping[str, Any]] = None) -> List[str]:
    """Every problem with one review record. Empty means valid.

    ``packet`` binds the record to what the reviewer was actually shown. Given
    one, the id, the narrative hash, the reviewer and the evidence turn ids are
    checked against it.
    """
    errs: List[str] = []
    if not isinstance(record, Mapping):
        return ["review record must be a JSON object"]
    extra = set(record) - RECORD_FIELDS
    missing = RECORD_FIELDS - set(record)
    if extra:
        errs.append(f"unknown fields {sorted(extra)}")
    if missing:
        return errs + [f"missing fields {sorted(missing)}"]

    if record["record_version"] != RECORD_VERSION:
        errs.append(f"record_version must be {RECORD_VERSION}")
    errs.extend(validate_person(record["reviewer"], "reviewer"))

    labels = record["labels"]
    if not isinstance(labels, Mapping) or set(labels) != set(CATEGORIES):
        errs.append(f"labels must have exactly the {len(CATEGORIES)} schema categories")
        labels = {}
    else:
        for c, v in labels.items():
            if not isinstance(v, bool):
                errs.append(f"label {c} must be a bool")

    routing = record["routing"]
    if routing not in ROUTINGS:
        errs.append(f"routing must be one of {ROUTINGS}")
    if labels and any(bool(labels.get(c)) for c in CRITICAL_CATEGORIES) and routing != "Critical":
        errs.append("a crisis or immediate-danger label must be routed Critical")

    if record["decision"] not in DECISIONS:
        errs.append(f"decision must be one of {DECISIONS}")
    if record["confidence"] not in CONFIDENCE:
        errs.append(f"confidence must be one of {CONFIDENCE}")
    if not isinstance(record["expected_abstention"], bool):
        errs.append("expected_abstention must be a bool")

    evidence = record["expected_evidence"]
    victim_ids = set()
    if packet is not None:
        victim_ids = {str(t["id"]) for t in packet.get("turns", []) if t.get("speaker") == "victim"}
    if not isinstance(evidence, Mapping):
        errs.append("expected_evidence must be an object of category -> turn ids")
    else:
        for cat, ids in evidence.items():
            if cat not in DETECTOR_CATEGORIES:
                errs.append(f"expected_evidence names non-detector category {cat!r}")
                continue
            if not labels.get(cat):
                errs.append(f"expected_evidence for {cat} but the label is false")
            if not isinstance(ids, list) or not ids:
                errs.append(f"expected_evidence for {cat} is empty")
                continue
            if len(set(ids)) != len(ids):
                errs.append(f"expected_evidence for {cat} repeats a turn id")
            for i in ids:
                if victim_ids and str(i) not in victim_ids:
                    errs.append(f"expected_evidence id {i!r} for {cat} is not a victim turn in this packet")
        for cat in DETECTOR_CATEGORIES:
            if labels.get(cat) and cat not in evidence:
                errs.append(f"label {cat} is true but has no expected_evidence")

    flags = record["ambiguity_flags"]
    if not isinstance(flags, list):
        errs.append("ambiguity_flags must be a list")
    else:
        for f in flags:
            if f not in AMBIGUITY_FLAGS:
                errs.append(f"unknown ambiguity flag {f!r}")
        if len(set(flags)) != len(flags):
            errs.append("duplicate ambiguity flag")

    reasoning = str(record["reasoning"]).strip()
    needs_reason = (record["decision"] != "accept" or record["confidence"] == "low"
                    or bool(record["expected_abstention"]) or bool(flags))
    if needs_reason and len(reasoning) < MIN_REASONING:
        errs.append(f"reasoning of at least {MIN_REASONING} characters is required for a rejection, a "
                    "discussion, low confidence, an abstention or any ambiguity flag")
    if not reasoning:
        errs.append("reasoning is required on every record")

    if record["attestation"] != ATTESTATION:
        errs.append("the reviewer attestation sentence is missing or altered")

    try:
        ts = datetime.fromisoformat(str(record["timestamp"]))
        if ts.tzinfo is None:
            errs.append("timestamp needs a timezone offset")
    except ValueError:
        errs.append("timestamp must be ISO 8601 with a timezone")

    if record["record_sha256"] != record_sha256(record):
        errs.append("record_sha256 does not match the record")

    if packet is not None:
        if record["packet_id"] != packet["packet_id"]:
            errs.append("packet_id does not match the packet this record was written against")
        if record["narrative_sha256"] != packet["narrative_sha256"]:
            errs.append("narrative_sha256 does not match the text in the packet (stale or edited packet)")
        if record["submission_id"] != packet["submission_id"]:
            errs.append("submission_id does not match the packet")
        if record["corpus_version"] != packet["corpus_version"]:
            errs.append("corpus_version does not match the packet")
        if not competent_for(record["reviewer"], packet["language"]):
            errs.append(f"reviewer is not recorded as competent in {packet['language']}")
    return errs


def finish_record(record: Mapping[str, Any]) -> Dict[str, Any]:
    """Return a copy with ``record_sha256`` filled in. For humans and tests.

    This computes a hash; it never supplies a judgement. A record whose
    judgement fields are blank still fails validation.
    """
    out = dict(record)
    out["record_sha256"] = record_sha256(out)
    return out


def decision_view(record: Mapping[str, Any]) -> Dict[str, Any]:
    """The comparable part of a record: what two reviewers must agree on."""
    return {
        "labels": dict(record.get("labels") or {}),
        "routing": record.get("routing"),
        "expected_abstention": bool(record.get("expected_abstention")),
        "expected_evidence": {k: sorted(v) for k, v in sorted((record.get("expected_evidence") or {}).items())},
        "decision": record.get("decision"),
    }


def critical_view(record: Mapping[str, Any]) -> Dict[str, Any]:
    """Only what the two-reviewer rule protects: the two critical labels and
    whether the case is routed Critical.

    The routing BAND is deliberately not part of this view. Two reviewers who
    both say "no crisis, no immediate danger, not Critical" but split Moderate
    against High disagree about priority, which is an ordinary conflict for an
    adjudicator — not a critical-label disagreement that needs a third blind
    review.
    """
    labels = record.get("labels") or {}
    view = {c: bool(labels.get(c)) for c in CRITICAL_CATEGORIES}
    view["routed_critical"] = record.get("routing") == "Critical"
    return view


def reviewers_of(records: Sequence[Mapping[str, Any]]) -> List[str]:
    """Distinct human person ids among a set of records, sorted."""
    return sorted({str(r["reviewer"]["person_id"]) for r in records if isinstance(r.get("reviewer"), Mapping)})
