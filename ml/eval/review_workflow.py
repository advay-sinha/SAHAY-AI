"""Fixture-level human review workflow for the candidate corpus. Stdlib only.

    python -m ml.eval.review_workflow export                 # packets -> runtime/review-packets/
    python -m ml.eval.review_workflow validate RECORD.json   # check a reviewer's record
    python -m ml.eval.review_workflow import RECORD.json     # append it to the ledger (once)
    python -m ml.eval.review_workflow status                 # review and lock-eligibility status
    python -m ml.eval.review_workflow validate-ledger [--expect-head COUNT:SHA256]

What it does and does not do
  * Exports one packet per candidate: stable fixture id, text, proposed labels,
    expected routing and evidence turns, contamination status, required
    reviews, and a BLANK record template.
  * A review record is written by a human reviewer. It binds to the exact
    fixture content by `fixture_sha256`, names the reviewer (GitHub username)
    and carries an explicit human attestation. Placeholder (`TODO-...`),
    bot or AI identities are refused. Nothing here ever creates a record.
  * The ledger (`ml/eval/reviews/fixture_reviews.jsonl`) is an append-only
    SHA-256 hash chain. Entry n holds `seq` (n, from 1), `prev_hash` (the
    previous entry's `entry_hash`; 64 zeros for the first), the record, its
    content-derived `record_id` and `entry_hash` = SHA-256 of the canonical
    entry without `entry_hash`. Reading re-verifies every link, so editing,
    deleting, reordering or inserting an entry anywhere except at the tail is
    detected, and the same record cannot be imported twice. Two limits are
    stated rather than hidden: removing trailing entries, or rewriting the
    whole chain with recomputed hashes, is only detectable against an
    externally recorded head (`status` prints it; Git history also holds it),
    which `validate-ledger --expect-head` checks. The chain is not signed.
  * Label or expectation changes need written reasoning, and they never
    rewrite the candidate: a changed fixture must be re-authored as a NEW
    fixture (new id / corpus version) and reviewed again.
  * It NEVER writes `locked.json`. `status` only reports eligibility.

Eligibility follows the repository's current rules without changing them:
  * review policy: `ml/eval/schema.py::required_reviews` (two distinct real
    approvals for crisis / immediate-danger fixtures, one otherwise), with no
    outstanding reject, needs-discussion or label change on the current
    fixture content;
  * contamination policy: `ml/eval/CONTAMINATION.md` forbids moving any
    sample of candidate corpus 2026.09.11-1 (all outcomes published) into
    the locked split, so `contamination.classify(...).independent_evidence`
    must also hold. Every current candidate therefore reports NOT eligible.
"""

import argparse
import hashlib
import json
import re
import sys
from datetime import datetime
from pathlib import Path
from typing import Any, Dict, List, Mapping, Optional

from . import contamination
from .schema import CATEGORIES, EXPECTED_KEYS, SCHEMA_VERSION, is_critical, required_reviews

EVAL = Path(__file__).resolve().parent
REPO = EVAL.parents[1]
CANDIDATES = EVAL / "corpus" / "candidates.json"
LEDGER = EVAL / "reviews" / "fixture_reviews.jsonl"
DEFAULT_EXPORT = REPO / "runtime" / "review-packets"

RECORD_VERSION = "1.0.0"
DECISIONS = ("approve", "reject", "needs_discussion")
ATTESTATION = "I personally reviewed this fixture; this record was not generated by an AI system."
RECORD_FIELDS = {"record_version", "fixture_id", "fixture_sha256", "schema_version", "reviewer", "reviewer_role",
                 "reviewer_kind", "attestation", "decision", "reasoning", "label_changes", "expected_changes",
                 "timestamp"}
_GITHUB_USER = re.compile(r"^[A-Za-z0-9](?:[A-Za-z0-9-]{0,37}[A-Za-z0-9])?$")
_NON_HUMAN = re.compile(r"(^todo)|(bot$)|(\[bot\])|claude|anthropic|openai|chatgpt|gpt|copilot|gemini|assistant|"
                        r"(^ai[-_]?)|llm|automated|placeholder", re.IGNORECASE)


class ReviewError(Exception):
    pass


def canonical(obj: Any) -> str:
    return json.dumps(obj, sort_keys=True, ensure_ascii=False, separators=(",", ":"))


def fixture_sha256(sample: Mapping[str, Any]) -> str:
    """Hash of the fixture CONTENT (everything except its review block)."""
    return hashlib.sha256(canonical({k: v for k, v in sample.items() if k != "review"}).encode("utf-8")).hexdigest()


def record_id(record: Mapping[str, Any]) -> str:
    return hashlib.sha256(canonical(record).encode("utf-8")).hexdigest()


def load_candidates(path: Path = CANDIDATES) -> Dict[str, Dict[str, Any]]:
    corpus = json.loads(Path(path).read_text(encoding="utf-8"))
    return {s["id"]: s for s in corpus["samples"]}


# --- export ---------------------------------------------------------------------------


def blank_record(sample: Mapping[str, Any]) -> Dict[str, Any]:
    return {"record_version": RECORD_VERSION, "fixture_id": sample["id"], "fixture_sha256": fixture_sha256(sample),
            "schema_version": SCHEMA_VERSION, "reviewer": "", "reviewer_role": "", "reviewer_kind": "human",
            "attestation": "", "decision": "", "reasoning": "", "label_changes": {}, "expected_changes": {},
            "timestamp": ""}


def packet(sample: Mapping[str, Any]) -> Dict[str, Any]:
    return {
        "packet_version": RECORD_VERSION,
        "fixture_id": sample["id"],
        "fixture_sha256": fixture_sha256(sample),
        "schema_version": sample["schema_version"],
        "language": sample["language"], "channel": sample["channel"], "tags": sample["tags"],
        "turns": sample["turns"],
        "proposed_labels": sample["labels"],
        "expected": sample["expected"],
        "expected_evidence": sample["expected_evidence"],
        "notes": sample["notes"],
        "critical": is_critical(sample),
        "required_reviews": required_reviews(sample),
        "contamination": contamination.classify(sample["id"]),
        "independent_evidence_possible": False if contamination.exposed(sample["id"]) else None,
        "reviewer_instructions": ("Fill a COPY of record_template yourself. Set attestation to the exact sentence "
                                  "given. A label or expectation change needs reasoning and does not edit the "
                                  "fixture. Never let an AI system fill this record."),
        "attestation_text": ATTESTATION,
        "record_template": blank_record(sample),
    }


def export(out_dir: Path = DEFAULT_EXPORT, candidates: Optional[Dict[str, Dict[str, Any]]] = None) -> List[Path]:
    candidates = candidates if candidates is not None else load_candidates()
    out_dir = Path(out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)
    written = []
    for sid in sorted(candidates):
        path = out_dir / f"{sid}.json"
        path.write_text(json.dumps(packet(candidates[sid]), indent=1, ensure_ascii=False, sort_keys=True) + "\n",
                        encoding="utf-8", newline="\n")
        written.append(path)
    return written


# --- records --------------------------------------------------------------------------


def validate_record(record: Mapping[str, Any], candidates: Mapping[str, Mapping[str, Any]]) -> List[str]:
    errs: List[str] = []
    if set(record) != RECORD_FIELDS:
        return [f"record fields must be exactly {sorted(RECORD_FIELDS)}"]
    if record["record_version"] != RECORD_VERSION:
        errs.append("unsupported record_version")
    if record["schema_version"] != SCHEMA_VERSION:
        errs.append(f"schema_version must be {SCHEMA_VERSION}")
    sample = candidates.get(record["fixture_id"])
    if sample is None:
        return errs + [f"unknown fixture {record['fixture_id']!r}"]
    if record["fixture_sha256"] != fixture_sha256(sample):
        errs.append("fixture_sha256 does not match the current fixture content (stale or edited)")
    reviewer = str(record["reviewer"])
    if not _GITHUB_USER.match(reviewer.lstrip("@")):
        errs.append("reviewer must be a GitHub username")
    if _NON_HUMAN.search(reviewer):
        errs.append("placeholder, bot or AI identities cannot review fixtures")
    if record["reviewer_kind"] != "human":
        errs.append("reviewer_kind must be 'human'")
    if record["attestation"] != ATTESTATION:
        errs.append("the human attestation sentence is missing or altered")
    if not str(record["reviewer_role"]).strip():
        errs.append("reviewer_role is required")
    if record["decision"] not in DECISIONS:
        errs.append(f"decision must be one of {DECISIONS}")
    for key, value in record["label_changes"].items():
        if key not in CATEGORIES or not isinstance(value, bool):
            errs.append(f"label_changes: {key!r} is not a schema category with a bool value")
        elif value == sample["labels"][key]:
            errs.append(f"label_changes: {key} does not change the current label")
    for key in record["expected_changes"]:
        if key not in EXPECTED_KEYS:
            errs.append(f"expected_changes: {key!r} is not an expected field")
    changes = bool(record["label_changes"] or record["expected_changes"])
    if (changes or record["decision"] != "approve") and len(str(record["reasoning"]).strip()) < 20:
        errs.append("reasoning (at least 20 characters) is required for rejection, discussion or any change")
    if changes and record["decision"] == "approve":
        errs.append("a record proposing changes cannot approve the fixture as-is; use needs_discussion")
    try:
        ts = datetime.fromisoformat(str(record["timestamp"]))
        if ts.tzinfo is None:
            errs.append("timestamp needs a timezone")
    except ValueError:
        errs.append("timestamp must be ISO 8601")
    return errs


GENESIS = "0" * 64
ENTRY_FIELDS = {"seq", "prev_hash", "record_id", "record", "entry_hash"}


def entry_hash(entry: Mapping[str, Any]) -> str:
    """SHA-256 over the canonical entry, excluding `entry_hash` itself."""
    return hashlib.sha256(canonical({k: v for k, v in entry.items() if k != "entry_hash"}).encode("utf-8")).hexdigest()


def read_ledger(path: Path = LEDGER) -> List[Dict[str, Any]]:
    """Read and verify the whole chain; any break raises ReviewError. An empty or absent ledger is valid."""
    path = Path(path)
    if not path.exists():
        return []
    entries: List[Dict[str, Any]] = []
    prev, seen = GENESIS, set()
    for n, line in enumerate(path.read_text(encoding="utf-8").splitlines(), 1):
        if not line.strip():
            continue
        try:
            entry = json.loads(line)
        except ValueError:
            raise ReviewError(f"ledger line {n}: not valid JSON") from None
        if not isinstance(entry, dict) or set(entry) != ENTRY_FIELDS or not isinstance(entry["record"], dict):
            raise ReviewError(f"ledger line {n}: entry fields must be exactly {sorted(ENTRY_FIELDS)}")
        if entry["seq"] != len(entries) + 1:
            raise ReviewError(f"ledger line {n}: seq {entry['seq']!r}, expected {len(entries) + 1} "
                              "(entry deleted, inserted or reordered)")
        if entry["prev_hash"] != prev:
            raise ReviewError(f"ledger line {n}: prev_hash does not link to the previous entry (chain broken)")
        if entry["record_id"] != record_id(entry["record"]):
            raise ReviewError(f"ledger line {n}: record_id does not match its record (record modified)")
        if entry["entry_hash"] != entry_hash(entry):
            raise ReviewError(f"ledger line {n}: entry_hash does not match the entry (entry modified)")
        if entry["record_id"] in seen:
            raise ReviewError(f"ledger line {n}: duplicate record")
        seen.add(entry["record_id"])
        prev = entry["entry_hash"]
        entries.append(entry)
    return entries


def ledger_head(path: Path = LEDGER) -> str:
    """`<count>:<last entry_hash>` of a verified ledger (`0:<64 zeros>` when empty). Record it externally."""
    entries = read_ledger(path)
    return f"{len(entries)}:{entries[-1]['entry_hash'] if entries else GENESIS}"


def verify_head(path: Path, expected: str) -> None:
    """Detect tail truncation or a recomputed rewrite against an externally recorded head."""
    try:
        count_s, head = expected.split(":")
        count = int(count_s)
    except ValueError:
        raise ReviewError("expected head must be <count>:<sha256>") from None
    entries = read_ledger(path)
    if count < 0 or len(entries) < count:
        raise ReviewError(f"ledger has {len(entries)} entries, the recorded head had {count} (truncated)")
    at = entries[count - 1]["entry_hash"] if count else GENESIS
    if at != head:
        raise ReviewError(f"entry {count} does not match the recorded head (ledger rewritten)")


def import_record(record: Mapping[str, Any], ledger: Path = LEDGER,
                  candidates: Optional[Mapping[str, Mapping[str, Any]]] = None) -> str:
    """Validate and append one human review record. Returns its record_id."""
    candidates = candidates if candidates is not None else load_candidates()
    errs = validate_record(record, candidates)
    if errs:
        raise ReviewError("; ".join(errs))
    rid = record_id(record)
    entries = read_ledger(ledger)  # verifies the existing chain first
    if any(e["record_id"] == rid for e in entries):
        raise ReviewError("this review record has already been imported")
    entry: Dict[str, Any] = {"seq": len(entries) + 1, "prev_hash": entries[-1]["entry_hash"] if entries else GENESIS,
                             "record_id": rid, "record": dict(record)}
    entry["entry_hash"] = entry_hash(entry)
    Path(ledger).parent.mkdir(parents=True, exist_ok=True)
    with open(ledger, "a", encoding="utf-8", newline="\n") as f:  # append-only
        f.write(canonical(entry) + "\n")
    return rid


# --- status ---------------------------------------------------------------------------


def status(ledger: Path = LEDGER, candidates: Optional[Mapping[str, Mapping[str, Any]]] = None) -> Dict[str, Any]:
    candidates = candidates if candidates is not None else load_candidates()
    entries = read_ledger(ledger)
    rows = {}
    for sid, sample in sorted(candidates.items()):
        current = fixture_sha256(sample)
        recs = [e["record"] for e in entries if e["record"]["fixture_id"] == sid]
        live = [r for r in recs if r["fixture_sha256"] == current]
        approvers = sorted({r["reviewer"].lstrip("@").casefold() for r in live
                            if r["decision"] == "approve" and not (r["label_changes"] or r["expected_changes"])})
        blocking = [r["decision"] if r["decision"] != "approve" else "change_proposed" for r in live
                    if r["decision"] != "approve" or r["label_changes"] or r["expected_changes"]]
        need = required_reviews(sample)
        reasons = []
        if len(approvers) < need:
            reasons.append(f"needs {need} distinct human approvals, has {len(approvers)}")
        if blocking:
            reasons.append("unresolved: " + ", ".join(sorted(set(blocking))))
        if len(recs) > len(live):
            reasons.append(f"{len(recs) - len(live)} record(s) for older fixture content ignored")
        info = contamination.classify(sid)
        if not info["independent_evidence"]:
            reasons.append("exposed/published sample: cannot be independent locked evidence (CONTAMINATION.md)")
        rows[sid] = {"critical": is_critical(sample), "required_reviews": need, "approvals": len(approvers),
                     "records": len(recs), "review_complete": len(approvers) >= need and not blocking,
                     "lock_eligible": not reasons, "reasons": reasons}
    return {"candidates": len(rows), "records_in_ledger": len(entries), "ledger_head": ledger_head(ledger),
            "lock_eligible": sorted(k for k, v in rows.items() if v["lock_eligible"]), "fixtures": rows,
            "note": "Eligibility is reported only. locked.json is never written by this tool."}


def main(argv: Optional[List[str]] = None) -> int:
    parser = argparse.ArgumentParser(description="SAHAY-AI fixture review workflow")
    sub = parser.add_subparsers(dest="cmd", required=True)
    e = sub.add_parser("export")
    e.add_argument("--out", default=str(DEFAULT_EXPORT))
    for name in ("validate", "import"):
        p = sub.add_parser(name)
        p.add_argument("record")
        p.add_argument("--ledger", default=str(LEDGER))
    s = sub.add_parser("status")
    s.add_argument("--ledger", default=str(LEDGER))
    v = sub.add_parser("validate-ledger")
    v.add_argument("--ledger", default=str(LEDGER))
    v.add_argument("--expect-head", default=None, metavar="COUNT:SHA256")
    args = parser.parse_args(argv)

    if args.cmd == "export":
        paths = export(Path(args.out))
        print(f"exported {len(paths)} review packets to {Path(args.out).name}/ (blank records; nothing approved)")
        return 0
    if args.cmd == "status":
        st = status(Path(args.ledger))
        print(f"candidates {st['candidates']}, ledger records {st['records_in_ledger']}, "
              f"lock-eligible {len(st['lock_eligible'])}, ledger head {st['ledger_head']}")
        return 0
    if args.cmd == "validate-ledger":
        try:
            if args.expect_head:
                verify_head(Path(args.ledger), args.expect_head)
            print(f"ledger chain valid; head {ledger_head(Path(args.ledger))}")
            return 0
        except ReviewError as exc:
            print(f"ledger invalid: {exc}")
            return 2
    record = json.loads(Path(args.record).read_text(encoding="utf-8"))
    try:
        if args.cmd == "validate":
            errs = validate_record(record, load_candidates())
            if errs:
                raise ReviewError("; ".join(errs))
            print("record valid (not imported)")
        else:
            print(f"imported {import_record(record, Path(args.ledger))}")
        return 0
    except ReviewError as exc:
        print(f"refused: {exc}")
        return 2


if __name__ == "__main__":
    sys.exit(main())
